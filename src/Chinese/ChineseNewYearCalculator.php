    public static function newYear(int $year): \DateTimeImmutable
    {
        if (!isset(self::$table[$year])) {
            throw new \InvalidArgumentException(\sprintf('Chinese New Year data for year %d is not available (supported range: 1900–2100).', $year));
        }

        [$month, $day] = self::$table[$year];

        return DatePoint::createFromFormat('!Y-m-d', \sprintf('%d-%02d-%02d', $year, $month, $day), new \DateTimeZone('UTC'));
    }

    public static function signForYear(int $year): ChineseZodiacSign
    {
        if (!isset(self::$table[$year])) {
            throw new \InvalidArgumentException(\sprintf('Chinese New Year data for year %d is not available (supported range: 1900–2100).', $year));
        }

        return ChineseZodiacSign::from(self::$table[$year][2]);
    }
